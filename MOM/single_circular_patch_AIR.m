% =========================================================================
% Автоматическое проектирование круглой патч-антенны силами Antenna Toolbox
% =========================================================================
clear; clc; close all;

fc = 2.4e9; % Заданная рабочая частота: 2.4 ГГц

% 1. Передаем управление тулбоксу: он сам рассчитывает все параметры подложки и диска
ant = design(patchMicrostripCircular, fc);
ant.Radius = 35.2e-3;
ant.FeedOffset = [10.7e-3, 0];
ant.Height = 2.0e-3;

% 2. Визуализация геометрии (Тулбокс сам откроет 3D-интерактивное окно)
figure('Name', 'Автоматическая геометрия антенны');
show(ant);
title(sprintf('Круглая патч-антенна: Авто-дизайн на %g ГГц', fc/1e9));

% 3. Построение 3D Диаграммы Направленности (ДН)
figure('Name', '3D Диаграмма направленности');
pattern(ant, fc);
title('3D ДН (Коэффициент усиления / Gain)');

% 4. ИЗВЛЕЧЕНИЕ И ВЫВОД ПАРАМЕТРОВ, КОТОРЫЕ ВЫБРАЛ ТУЛБОКС
fprintf('\n==================================================\n');
fprintf('                       ПАРАМЕТРЫ                   \n');
fprintf('==================================================\n');

% Проверяем, какой диэлектрик выбрал MATLAB (по умолчанию обычно воздух/тефлон)
if ischar(ant.Substrate.Name) || isstring(ant.Substrate.Name)
    fprintf('Материал подложки (Substrate): %s\n', ant.Substrate.Name);
else
    fprintf('Материал подложки (Substrate): Пользовательский диэлектрик\n');
end
fprintf('Диэлектрическая проницаемость (epsR): %.2f\n', ant.Substrate.EpsilonR);
fprintf('Толщина подложки (Height):           %.3f мм\n', ant.Height * 1e3);

fprintf('--------------------------------------------------\n');
fprintf('Радиус патча (Radius):                %.2f мм\n', ant.Radius * 1e3);
fprintf('Диаметр излучающего диска:            %.2f мм\n', (ant.Radius * 2) * 1e3);

fprintf('--------------------------------------------------\n');
fprintf('Точка запитки (Feed Offset):\n');
fprintf('  - Смещение по оси X:                %.2f мм от центра\n', ant.FeedOffset(1) * 1e3);
fprintf('  - Смещение по оси Y:                %.2f мм\n', ant.FeedOffset(2) * 1e3);

fprintf('--------------------------------------------------\n');
fprintf('Размеры экрана (Ground Plane):\n');
fprintf('  - Длина (Ground Length):            %.2f мм\n', ant.GroundPlaneLength * 1e3);
fprintf('  - Ширина (Ground Width):            %.2f мм\n', ant.GroundPlaneWidth * 1e3);
fprintf('==================================================\n');

% =========================================================================
% Построение ДН в декартовых координатах (угол от 0 до 180 градусов)
% =========================================================================

% 1. Задаем вектор углов от 0 до 180 градусов с шагом 1 градус
elevation_angles = 0:1:180;

% 2. Извлекаем значения усиления (Gain) для плоскостей E и H
% Функция pattern возвращает матрицу. Чтобы получить вертикальный разрез, 
% фиксируем Азимут (0 для E-плоскости, 90 для H-плоскости).
E_plane_data = pattern(ant, fc, 0, elevation_angles);  % Azimuth = 0
H_plane_data = pattern(ant, fc, 90, elevation_angles); % Azimuth = 90

% 3. Построение обычного (декартового) графика
figure('Name', 'ДН в декартовых координатах');
plot(elevation_angles, E_plane_data, 'r-', 'LineWidth', 2);
hold on;
plot(elevation_angles, H_plane_data, 'b--', 'LineWidth', 2);

% Настройки осей и оформления
grid on;
xlim([0 180]);
ylim([-20 max([E_plane_data; H_plane_data])+2]); % Автоматический масштаб по вертикали с запасом

xlabel('Угол Элевации \theta (градусы)');
ylabel('Коэффициент усиления (dBi)');
title('Разрез ДН круглой патч-антенны (0^\circ - 180^\circ)');
legend('E-плоскость (\phi = 0^\circ)', 'H-плоскость (\phi = 90^\circ)', 'Location', 'southoutside');

% Считаем потери на отражение для портов антенны на рабочей частоте
RL = returnLoss(ant, fc);

% MATLAB возвращает Return Loss как положительное число (затухание несогласованности).
% Чтобы перевести его в привычный инженерам отрицательный S11 (дБ), ставим знак минус.
S11_central = -RL(1); 

fprintf('Коэффициент отражения S11 для центрального элемента: %.2f дБ\n', S11_central);


